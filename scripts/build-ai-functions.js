const fs = require('node:fs')
const path = require('node:path')
const base = path.resolve(__dirname, '..')
const source = path.join(base, 'server', 'ai')
for (const name of ['ciyun-ai', 'ciyun-image-worker']) {
  const target = path.join(base, 'cloudfunctions', name)
  const shared = path.join(target, 'server', 'ai')
  fs.mkdirSync(shared, { recursive: true })
  fs.cpSync(source, shared, { recursive: true })
  fs.mkdirSync(path.join(target, 'data'), { recursive: true })
  for (const file of ['ai-create.js', 'ceramics.js']) fs.copyFileSync(path.join(base, 'data', file), path.join(target, 'data', file))
  const mode = name === 'ciyun-ai' ? 'api' : 'worker'
  fs.writeFileSync(path.join(target, 'index.js'), `// Generated by scripts/build-ai-functions.js. Edit server/ai instead.\nconst cloud = require('wx-server-sdk')\nconst { createRuntime } = require('./server/ai/runtime')\ncloud.init({ env: cloud.DYNAMIC_CURRENT_ENV })\nconst runtime = createRuntime({ cloud })\nexports.main = async event => runtime.${mode}(event)\n`)
  fs.writeFileSync(path.join(target, 'package.json'), JSON.stringify({ name, version: '1.0.0', private: true, main: 'index.js', engines: { node: '>=20.19' }, dependencies: { 'wx-server-sdk': '4.0.2' } }, null, 2) + '\n')
}
console.log('Built ciyun-ai and ciyun-image-worker; install wx-server-sdk 4.0.2 during deployment.')
